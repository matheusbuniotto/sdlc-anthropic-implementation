// Generates mods/okf-loop/hooks/core/knowledge.generated.ts from openknowledge/.
//
//   bun scripts/build-knowledge.ts            write the snapshot
//   bun scripts/build-knowledge.ts --check    exit 1 if the committed snapshot is stale
//
// The parser is the mod's own loadKnowledge, so the bundled snapshot and the
// runtime override path (a project's openknowledge/) can never disagree.
// Output is deterministic: sorted inputs, no timestamps.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ROOT_DIR = 'openknowledge'
const KNOWLEDGE = join(REPO, ROOT_DIR)
const OUT = join(REPO, 'mods/okf-loop/hooks/core/knowledge.generated.ts')
const CHECK = process.argv.includes('--check')

const STUB = `import type { PlayDef, StageDoc, TemplateName } from '../../types'
export const BUNDLED: { title: string; version: string; summary: string; plays: PlayDef[]; stages: StageDoc[]; templates: Partial<Record<TemplateName, string>> } = { title: '', version: '', summary: '', plays: [], stages: [], templates: {} }
`

// knowledge.ts imports the generated file, so a missing one is bootstrapped before it is imported.
if (!existsSync(OUT)) writeFileSync(OUT, STUB)
const { loadKnowledge, validatePlayGraph } = await import('../mods/okf-loop/hooks/core/knowledge')
const { TEMPLATE_FILES, TEMPLATE_NAMES } = await import('../mods/okf-loop/hooks/core/constants')

function listFiles(dir: string, pattern: RegExp): string[] {
  const base = join(KNOWLEDGE, dir)
  if (!existsSync(base)) return []
  return readdirSync(base)
    .filter((f) => pattern.test(f))
    .sort()
    .map((f) => `${dir}/${f}`)
}

const rel = ['INDEX.md', ...listFiles('plays', /^play-\d+-.+\.md$/), ...listFiles('stages', /^\d+-.+\.md$/), ...listFiles('templates', /^[^.].*$/)]
const files: Record<string, string> = {}
for (const p of rel) {
  const full = join(KNOWLEDGE, p)
  if (existsSync(full)) files[p] = readFileSync(full, 'utf8')
}

const knowledge = loadKnowledge(files, ROOT_DIR)
const problems: string[] = [...knowledge.issues, ...validatePlayGraph(knowledge.plays)]
if (knowledge.plays.length !== 14) problems.push(`expected 14 plays, found ${knowledge.plays.length}`)
if (knowledge.stages.length !== 6) problems.push(`expected 6 stages, found ${knowledge.stages.length}`)
for (const name of TEMPLATE_NAMES) {
  if (knowledge.templates[name] === undefined) problems.push(`template "${name}" (${TEMPLATE_FILES[name]}) not found`)
}

// INDEX.md carries the graph a second time (Playbook Directory); front-matter stays the truth.
const notes: string[] = []
const index = files['INDEX.md'] ?? ''
for (const line of index.split('\n')) {
  const head = /^- \[\*\*Play (\d+):/.exec(line)
  if (!head) continue
  const n = Number(head[1])
  const play = knowledge.plays.find((p) => p.n === n)
  const tail = /\*\((Entry Point|Depends on Plays? [\d, and]+)\)\*/.exec(line)
  if (!play || !tail) {
    notes.push(`INDEX.md lists Play ${n} but its front-matter or its "(Depends on …)" note is missing`)
    continue
  }
  const listed = tail[1] === 'Entry Point' ? [] : (tail[1]?.match(/\d+/g) ?? []).map(Number)
  const same = listed.length === play.prerequisites.length && listed.every((q) => play.prerequisites.includes(q))
  if (!same) notes.push(`INDEX.md says Play ${n} depends on [${listed.join(', ')}], front-matter says [${play.prerequisites.join(', ')}]`)
  if ((tail[1] === 'Entry Point') !== play.entryPoint) notes.push(`INDEX.md and front-matter disagree on whether Play ${n} is an entry point`)
}
// The mermaid graph only draws part of the edges; report the ones it omits so a reader is not misled.
const drawn = new Set<string>()
for (const m of index.matchAll(/\bP(\d+)(?:\[[^\]]*\])?\s*(?:-->|-\.->)\s*P(\d+)\b/g)) drawn.add(`${m[1]}>${m[2]}`)
const undrawn: string[] = []
for (const p of knowledge.plays) for (const q of p.prerequisites) if (!drawn.has(`${q}>${p.n}`)) undrawn.push(`${q}->${p.n}`)

// --- emit ----------------------------------------------------------------

function q(s: string): string {
  const body = s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'))
  return `'${body}'`
}

const list = (xs: string[]): string => (xs.length === 0 ? '[]' : `[${xs.map(q).join(', ')}]`)

function lines(src: string, indent: string): string {
  const parts = src.split('\n')
  return `[\n${parts.map((l) => `${indent}  ${q(l)},`).join('\n')}\n${indent}].join('\\n')`
}

const out: string[] = []
out.push(`// GENERATED by scripts/build-knowledge.ts from ${ROOT_DIR}/ — do not edit.`)
out.push(`// Regenerate: bun scripts/build-knowledge.ts   (from the repository root)`)
out.push('')
out.push(`import type { PlayDef, StageDoc, TemplateName } from '../../types'`)
out.push('')
out.push('export const BUNDLED: {')
out.push('  title: string')
out.push('  version: string')
out.push('  summary: string')
out.push('  plays: PlayDef[]')
out.push('  stages: StageDoc[]')
out.push('  templates: Partial<Record<TemplateName, string>>')
out.push('} = {')
out.push(`  title: ${q(knowledge.title)},`)
out.push(`  version: ${q(knowledge.version)},`)
out.push(`  summary: ${q(knowledge.summary)},`)
out.push('  plays: [')
for (const p of knowledge.plays) {
  out.push('    {')
  out.push(`      n: ${p.n},`)
  out.push(`      id: ${q(p.id)},`)
  out.push(`      title: ${q(p.title)},`)
  out.push(`      stage: ${q(p.stage)},`)
  out.push(`      entryPoint: ${p.entryPoint},`)
  out.push(`      prerequisites: [${p.prerequisites.join(', ')}],`)
  out.push(`      outputs: ${list(p.outputs)},`)
  out.push(`      summary: ${q(p.summary)},`)
  out.push(`      path: ${q(p.path)},`)
  out.push(`      tags: ${list(p.tags)},`)
  out.push('    },')
}
out.push('  ],')
out.push('  stages: [')
for (const s of knowledge.stages) {
  out.push(`    { id: ${q(s.id)}, number: ${s.number}, title: ${q(s.title)}, summary: ${q(s.summary)}, path: ${q(s.path)} },`)
}
out.push('  ],')
out.push('  templates: {')
for (const name of TEMPLATE_NAMES) {
  const body = knowledge.templates[name]
  if (body === undefined) continue
  const key = /^[a-z]+$/.test(name) ? name : q(name)
  out.push(`    ${key}: ${lines(body, '    ')},`)
}
out.push('  },')
out.push('}')
out.push('')
const generated = out.join('\n')

console.log(`knowledge: ${knowledge.title} v${knowledge.version}`)
console.log(`  plays ${knowledge.plays.length} (entry points: ${knowledge.plays.filter((p) => p.entryPoint).map((p) => p.n).join(', ')})`)
for (const p of knowledge.plays) {
  console.log(`    ${String(p.n).padStart(2)} ${p.stage.padEnd(8)} needs [${p.prerequisites.join(', ')}]  ${p.title}`)
}
console.log(`  stages ${knowledge.stages.length}, templates ${Object.keys(knowledge.templates).length}/${TEMPLATE_NAMES.length}`)
if (undrawn.length > 0) console.log(`  note: INDEX.md's mermaid graph omits edges ${undrawn.join(', ')} (its Playbook Directory and the front-matter list them)`)
for (const n of notes) console.log(`  MISMATCH: ${n}`)
for (const p of problems) console.log(`  PROBLEM: ${p}`)

if (problems.length > 0 || notes.length > 0) {
  console.error(`build-knowledge: ${problems.length} problem(s), ${notes.length} INDEX mismatch(es); ${CHECK ? 'nothing checked' : 'nothing written'}`)
  process.exit(1)
}

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (CHECK) {
  if (current !== generated) {
    console.error('build-knowledge: knowledge.generated.ts is stale; run: bun scripts/build-knowledge.ts')
    process.exit(1)
  }
  console.log('knowledge.generated.ts is up to date')
} else {
  if (current === generated) console.log('knowledge.generated.ts unchanged')
  else {
    writeFileSync(OUT, generated)
    console.log(`wrote ${OUT.replace(`${REPO}/`, '')} (${generated.split('\n').length} lines)`)
  }
}
